# For loops :- It is used for sequential traversal. For traversing list, string ,tuples etc.

# Example of list :- 
nums = [1,2,3,4,5]

for val in nums:
    print(val)

# Example of str :-
str = "Apnacollege"
for char in str :
    print(char) # then individual character of string will print

# Example of Tuple :-

p = (11,12,13,14,15)
for digit in p :
    print(digit)

