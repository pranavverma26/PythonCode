# Q 3).  print the elements of the following list using a loop . 
       # [1,4,9,16,25,36,49,64,81,100]
# SOLUTION :-

nums = [1,4,9,16,25,36,49,64,81,100]

idx = 0
while idx < len(nums):
    print(nums[idx])   # nums[0] , nums[1] , nums[2]..
    idx += 1

Heroes = ["Ironman" , "Thor" , "Superman" , "Batman"]
p = 0
